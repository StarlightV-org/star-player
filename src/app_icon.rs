//! The executable resource also supplies the title-bar and taskbar icons.
#[cfg(windows)]
pub fn apply(window: &gpui_kit::Window) {
    use raw_window_handle::{HasWindowHandle, RawWindowHandle};
    use windows_sys::Win32::{System::LibraryLoader::GetModuleHandleW, UI::WindowsAndMessaging::*};

    let Ok(handle) = HasWindowHandle::window_handle(window) else {
        return;
    };
    let RawWindowHandle::Win32(handle) = handle.as_raw() else {
        return;
    };
    unsafe {
        let module = GetModuleHandleW(std::ptr::null());
        for (kind, width, height) in [
            (ICON_SMALL, SM_CXSMICON, SM_CYSMICON),
            (ICON_BIG, SM_CXICON, SM_CYICON),
        ] {
            // Resource ID 1 is generated by winresource. Shared icons are owned
            // by Windows and remain valid for the lifetime of the application.
            let icon = LoadImageW(
                module,
                1usize as *const u16,
                IMAGE_ICON,
                GetSystemMetrics(width),
                GetSystemMetrics(height),
                LR_SHARED,
            );
            if icon.is_null() {
                crate::logging::Print(
                    crate::logging::Level::Warn,
                    format!("Load application icon: {}", std::io::Error::last_os_error()),
                );
                continue;
            }
            SendMessageW(
                handle.hwnd.get() as _,
                WM_SETICON,
                kind as usize,
                icon as isize,
            );
        }
    }
}

#[cfg(not(windows))]
pub fn apply(_: &gpui_kit::Window) {}
